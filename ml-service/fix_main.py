seen = set()
langs_data = []
for k, v in langs_raw:
    if k not in seen:
        seen.add(k)
        langs_data.append((k, v))

lang_options = "".join([f'<option value="{k}">{v}</option>' for k, v in langs_data])
gender_options = '<option value="male">صوت رجالي</option><option value="female">صوت نسائي</option>'

files = glob.glob('app/**/*.py', recursive=True) + glob.glob('app/**/*.html', recursive=True)

for path in files:
    if path.endswith(('.bak', '.corrupted')):
        continue
    with open(path, 'r', encoding='utf-8', errors='ignore') as f:
        content = f.read()

    content = re.sub(r'(<select[^>]*id=["\']targetLang["\'][^>]*>)(.*?)(</select>)', r'\1' + lang_options + r'\3', content, flags=re.DOTALL)
    content = re.sub(r'(<select[^>]*id=["\']gender["\'][^>]*>)(.*?)(</select>)', r'\1' + gender_options + r'\3', content, flags=re.DOTALL)

    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"✅ Updated with {len(langs_data)} languages: {path}")
